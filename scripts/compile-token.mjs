import solc from "solc";
import { readFileSync, writeFileSync } from "node:fs";
const src = readFileSync("contracts/NimBrosToken.sol", "utf8");
const input = { language: "Solidity", sources: { "NimBrosToken.sol": { content: src } }, settings: { evmVersion: "paris", optimizer: { enabled: true, runs: 200 }, outputSelection: { "*": { "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object"] } } } };
const out = JSON.parse(solc.compile(JSON.stringify(input)));
const errs = (out.errors ?? []).filter((e) => e.severity === "error");
if (errs.length) { console.error(errs.map((e) => e.formattedMessage).join("\n")); process.exit(1); }
const c = out.contracts["NimBrosToken.sol"].NimBrosToken;
const ts = `/* GENERATED by scripts/compile-token.mjs from contracts/NimBrosToken.sol (solc ${solc.version()}, evm paris, optimizer 200). Do not edit by hand. */
export const TOKEN_BYTECODE = "0x${c.evm.bytecode.object}";
export const TOKEN_ABI_FUNCTIONS = ${JSON.stringify(c.abi.filter((x) => x.type === "function").map((x) => x.name).sort())};
`;
writeFileSync("lib/erc20Bytecode.ts", ts);
console.log("bytecode bytes:", c.evm.bytecode.object.length / 2, "functions:", c.abi.filter((x) => x.type === "function").map((x) => x.name).join(","));
